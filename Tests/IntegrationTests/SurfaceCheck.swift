// types. This half covers RefereeCore (besides Appendix A), PaperText, CitationKit, LLMKit, CLIProviders, ReviewEngine,
// ScholarKit, Persistence and the Composition file printed after section 11.3; the other half, for RefereeUI, AppCore,
