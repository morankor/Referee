private func isActor<T: Actor>(_: T.Type) {}
private func isClass<T: AnyObject>(_: T.Type) {}

func surfaceCheckOfTheLibraries(raw: RawDocument, paper: PaperText, loaded: LoadedPaper, environment: ProviderEnvironment, folder: URL) async {
    // ---- RefereeCore, besides Appendix A (Wave 0a) ----
    let _: AppSettings = DefaultSettings.make()
    let _: [String] = [FormatSpec.review, FormatSpec.revision, FormatSpec.taskReviewText, FormatSpec.taskReviewPDF, FormatSpec.taskPart,
                       FormatSpec.taskWhole, FormatSpec.taskContinue]

    // ---- PaperText (WP1) ----
    let builder: any PaperTextBuilding = PaperTextBuilder(stripMarginLineNumbers: { true })
    let _: any PaperTextBuilding = PaperTextBuilder()
    let _: PaperText = builder.build(from: raw)
    let matcher: any QuoteMatching = QuoteMatcher(paper: paper)
    let _: AnchorMatch? = matcher.locate(quote: "", pageHint: nil)
    let renderer: any PaperRendering = PaperRenderer()
    let _: String = renderer.render(paper, pages: nil)

    // ---- CitationKit (WP3) ----
    let _: any CitationIndexing = CitationIndexer()

    // ---- LLMKit (WP4) ----
    let _: [any LLMProvider] = LLMKitFactory.makeProviders(environment: environment)
    let _: any SecretStoring = KeychainSecretStore(service: "local.referee.app", account: "secrets-v1")
    let _: any SecretStoring = KeychainSecretStore()
    isClass(KeychainSecretStore.self)

    // ---- CLIProviders (WP5) ----
    let _: [any LLMProvider] = CLIProviderFactory.makeProviders(environment: environment)

    // ---- ReviewEngine (WP6) ----
    let matcherFactory: @Sendable (PaperText) -> any QuoteMatching = { QuoteMatcher(paper: $0) }
    let _: any ReviewEngineProtocol = ReviewEngine(providers: ProviderRegistry([]), paperService: FakePaperService(paper: loaded),
                                                   matcherFactory: matcherFactory, renderer: PaperRenderer(), physicalMemoryBytes: 24 << 30)
    let _: any ReviewEngineProtocol = ReviewEngine(providers: ProviderRegistry([]), paperService: FakePaperService(paper: loaded),
                                                   matcherFactory: matcherFactory, renderer: FakePaperRenderer())
    isClass(ReviewEngine.self)

    // ---- ScholarKit (WP7) ----
    let _: any ReferenceResolving = ReferenceResolver(settings: { ReferenceSettings(crossrefMailto: "", pdfCacheLimitMB: 500) },
                                                      urlSession: StubURLProtocol.session(), dataDirectory: folder,
                                                      cacheDirectory: folder.appendingPathComponent("Caches", isDirectory: true))
    isActor(ReferenceResolver.self)

    // ---- Persistence (WP8a) ----
    let _: URL = AppPaths.dataDirectory(environment: ["REFEREE_HOME": folder.path])
    let _: URL = AppPaths.cacheDirectory(environment: ["REFEREE_HOME": folder.path])
    let _: any SessionStoring = FileSessionStore(directory: folder.appendingPathComponent("sessions", isDirectory: true))
    let _: any SettingsStoring = FileSettingsStore(fileURL: folder.appendingPathComponent("settings.json"))
    isActor(FileSessionStore.self)
    isActor(FileSettingsStore.self)

    // ---- Composition (printed in full after section 11.3) ----
    let _: AppDependencies = await LiveDependencies.make(environment: ["REFEREE_HOME": folder.path, "REFEREE_SNAPSHOT": "1"])
    let _: AppDependencies = await LiveDependencies.make()
    let _: URLSession = LiveDependencies.makeURLSession()
}
